import { promises as fs } from 'node:fs';
import type { Finding, ScannerAdapter, ScanOptions } from './scanner.js';
import { SarifReportAdapter } from './report-adapters.js';
export type EvidenceFormat =
  'sarif' | 'npm-audit' | 'pnpm-audit' | 'trivy' | 'lighthouse' | 'review';
export interface EvidenceReport {
  format: EvidenceFormat;
  path: string;
  maxBytes?: number;
  maxAgeMs?: number;
}
const severity = (s: unknown): Finding['severity'] => {
  const v = String(s).toLowerCase();
  return ['critical', 'high', 'medium', 'low', 'info'].includes(v)
    ? (v as Finding['severity'])
    : v === 'moderate'
      ? 'medium'
      : 'info';
};
const obj = (v: unknown): Record<string, any> =>
  v && typeof v === 'object' && !Array.isArray(v) ? (v as Record<string, any>) : {};
const array = (v: unknown): any[] => (Array.isArray(v) ? v : []);
/** Import tool evidence only from deployment-configured paths, not from HTTP input. Review reports must be generated by a trusted assessment. */
export class EvidenceReportAdapter implements ScannerAdapter {
  constructor(
    private scannerId: string,
    private report: EvidenceReport,
  ) {}
  async scan(options: Readonly<ScanOptions>): Promise<Finding[]> {
    const stat = await fs.stat(this.report.path);
    if (!stat.isFile() || stat.size > (this.report.maxBytes ?? 8_000_000))
      throw Error('Invalid report file');
    if (Date.now() - stat.mtimeMs > (this.report.maxAgeMs ?? 86400000)) throw Error('Report stale');
    if (this.report.format === 'sarif')
      return new SarifReportAdapter(this.scannerId, this.report.path, this.report.maxBytes).scan(
        options,
      );
    const data = obj(JSON.parse(await fs.readFile(this.report.path, 'utf8')));
    const findings: Finding[] = [];
    const add = (
      check: unknown,
      level: unknown,
      title: string,
      location: string,
      remediation: string,
    ) => {
      if (findings.length >= 2000) throw Error('Evidence finding limit exceeded');
      const checkId = String(check)
        .replace(/[^\w.-]/g, '_')
        .slice(0, 150);
      findings.push({
        id: `${this.scannerId}:${checkId}:${findings.length + 1}`,
        scannerId: this.scannerId,
        checkId,
        severity: severity(level),
        title,
        location: location.slice(0, 300),
        evidence: 'Tool report evidence withheld',
        confidence: 'medium',
        remediation,
      });
    };
    if (this.report.format === 'npm-audit') {
      if (
        data.auditReportVersion !== 2 ||
        !data.vulnerabilities ||
        typeof data.vulnerabilities !== 'object' ||
        Array.isArray(data.vulnerabilities) ||
        data.error
      )
        throw Error('Expected npm audit v2 report');
      for (const [name, v] of Object.entries(obj(data.vulnerabilities))) {
        const x = obj(v);
        add(
          name,
          x.severity,
          `Dependency vulnerability: ${name}`,
          'dependency-lockfile',
          'Review advisory and upgrade affected packages.',
        );
      }
    } else if (this.report.format === 'pnpm-audit') {
      if (
        data.error ||
        data.code ||
        !data.advisories ||
        typeof data.advisories !== 'object' ||
        Array.isArray(data.advisories) ||
        !data.metadata ||
        typeof data.metadata !== 'object'
      )
        throw Error('Expected pnpm audit advisories report');
      for (const [key, value] of Object.entries(obj(data.advisories))) {
        const advisory = obj(value);
        if (
          typeof advisory.module_name !== 'string' ||
          !advisory.module_name ||
          !['critical', 'high', 'moderate', 'medium', 'low', 'info'].includes(
            String(advisory.severity).toLowerCase(),
          )
        )
          throw Error('Malformed pnpm advisory');
        add(
          key,
          advisory.severity,
          `Dependency vulnerability: ${advisory.module_name}`,
          'dependency-lockfile',
          'Review advisory and upgrade affected packages.',
        );
      }
    } else if (this.report.format === 'trivy') {
      if (!Array.isArray(data.Results) || !data.Results.length)
        throw Error('Expected nonempty Trivy JSON results');
      for (const result of data.Results) {
        if (
          !result ||
          typeof result.Target !== 'string' ||
          !result.Target ||
          ['Vulnerabilities', 'Misconfigurations', 'Secrets'].some(
            (k) => result[k] !== undefined && result[k] !== null && !Array.isArray(result[k]),
          )
        )
          throw Error('Invalid Trivy target result');
        for (const v of array(result.Vulnerabilities))
          add(
            v.VulnerabilityID,
            v.Severity,
            'Dependency or image vulnerability',
            String(result.Target ?? 'image'),
            'Upgrade or mitigate affected package.',
          );
        for (const v of array(result.Misconfigurations))
          add(
            v.ID,
            v.Severity,
            'Configuration finding',
            String(result.Target ?? 'config'),
            'Review scanner recommendation.',
          );
        for (const v of array(result.Secrets))
          add(
            v.RuleID,
            v.Severity,
            'Secret exposure candidate',
            'report',
            'Rotate confirmed exposed credentials.',
          );
      }
    } else if (this.report.format === 'lighthouse') {
      if (!data.lighthouseVersion || !data.audits || data.runtimeError)
        throw Error('Expected successful Lighthouse JSON');
      const cat =
        this.scannerId === 'SCAN-39'
          ? 'performance'
          : this.scannerId === 'SCAN-40'
            ? 'accessibility'
            : this.scannerId === 'SCAN-36'
              ? 'seo'
              : null;
      if (!cat || !data.categories?.[cat]) throw Error('Missing requested Lighthouse category');
      const refs = data.categories[cat].auditRefs;
      if (!Array.isArray(refs) || !refs.length) throw Error('Missing Lighthouse audit refs');
      for (const ref of refs) {
        if (typeof ref?.id !== 'string' || !Object.hasOwn(data.audits, ref.id))
          throw Error('Missing Lighthouse audit');
        const a = obj(data.audits[ref.id]);
        if (a.scoreDisplayMode === 'error' || a.errorMessage)
          throw Error('Lighthouse audit failed to execute');
        if (typeof a.score === 'number' && a.score < 0.9 && a.scoreDisplayMode !== 'notApplicable')
          add(
            ref.id,
            a.score === 0 ? 'medium' : 'low',
            `Lighthouse ${cat} audit failed`,
            'lighthouse-report',
            'Review the original Lighthouse report and retest.',
          );
      }
    } else {
      if (
        data.scannerId !== this.scannerId ||
        data.completed !== true ||
        !Array.isArray(data.checks) ||
        !data.checks.length
      )
        throw Error('Review evidence incomplete');
      for (const check of data.checks) {
        if (
          typeof check.id !== 'string' ||
          !['pass', 'fail', 'not-applicable'].includes(check.status)
        )
          throw Error('Review check malformed');
        if (check.status === 'fail')
          add(
            check.id,
            check.severity,
            'Review evidence check failed',
            'assessment-report',
            'Review evidence and address the failed control.',
          );
      }
    }
    return findings;
  }
}
